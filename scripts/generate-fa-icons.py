#!/usr/bin/env python3
"""
Generate Font Awesome Free icon lookup for the UI Component Kit.

Reads Font Awesome Free `metadata/icon-families.json` (from the npm package
or desktop download) and emits:
  src/ui-component-kit/fonts/fontAwesome.icons.ts

Usage:
  python scripts/generate-fa-icons.py path/to/icon-families.json
"""

from __future__ import annotations

import json
import sys
from pathlib import Path


STYLES = ('solid', 'regular', 'brands')


# MARK: kebab_to_camel
def kebab_to_camel(name: str) -> str:
	"""Convert kebab-case FA name to camelCase (dice-d20 -> diceD20)."""
	parts = name.split('-')
	if not parts:
		return name
	return parts[0] + ''.join(p[:1].upper() + p[1:] for p in parts[1:] if p)


# MARK: collect_free_styles
def collect_free_styles(entry: dict) -> list[str]:
	"""Return free classic styles present for an icon, in STYLES order."""
	free = (entry.get('familyStylesByLicense') or {}).get('free') or []
	found = set()
	for item in free:
		if item.get('family') != 'classic':
			continue
		style = item.get('style')
		if style in STYLES:
			found.add(style)
	return [s for s in STYLES if s in found]


# MARK: generate
def generate(meta_path: Path, out_path: Path) -> int:
	"""Write the TypeScript icon map from FA metadata."""
	data = json.loads(meta_path.read_text(encoding='utf-8'))

	# canonical kebab name -> { unicode, styles }
	canonical: dict[str, dict] = {}
	# alias / camel -> canonical kebab
	aliases: dict[str, str] = {}

	for name, entry in sorted(data.items()):
		styles = collect_free_styles(entry)
		if not styles:
			continue
		unicode_hex = str(entry.get('unicode') or '').lower()
		if not unicode_hex:
			continue
		canonical[name] = {
			'unicode': unicode_hex,
			'styles' : styles,
		}
		aliases[kebab_to_camel(name)] = name
		alias_names = ((entry.get('aliases') or {}).get('names')) or []
		for alias in alias_names:
			aliases[alias] = name
			aliases[kebab_to_camel(alias)] = name

	lines: list[str] = []
	lines.append('/* eslint-disable */')
	lines.append('/**')
	lines.append(' * GENERATED by scripts/generate-fa-icons.py — do not edit by hand.')
	lines.append(' * Source: Font Awesome Free metadata/icon-families.json (classic free styles).')
	lines.append(' */')
	lines.append('')
	lines.append("export type FontAwesomeStyle = 'solid' | 'regular' | 'brands'")
	lines.append('')
	lines.append('export type FontAwesomeIconEntry = {')
	lines.append('\t/** Hex codepoint without `U+` / `0x` (Private Use Area for most icons). */')
	lines.append('\tunicode: string')
	lines.append('\t/** Free classic styles that include this glyph. */')
	lines.append('\tstyles : FontAwesomeStyle[]')
	lines.append('}')
	lines.append('')
	lines.append('/** Canonical kebab-case icon name -> unicode + free styles. */')
	lines.append('export const FONT_AWESOME_ICONS: Record<string, FontAwesomeIconEntry> = {')
	for name, info in canonical.items():
		styles_lit = ', '.join(f"'{s}'" for s in info['styles'])
		lines.append(f"\t'{name}': {{ unicode: '{info['unicode']}', styles: [{styles_lit}] }},")
	lines.append('}')
	lines.append('')
	lines.append('/** Alias / camelCase name -> canonical kebab-case key in FONT_AWESOME_ICONS. */')
	lines.append('export const FONT_AWESOME_ALIASES: Record<string, string> = {')
	for alias, canon in sorted(aliases.items()):
		if alias == canon:
			continue
		# Skip alias that would collide with a different canonical icon name
		if alias in canonical:
			continue
		lines.append(f"\t'{alias}': '{canon}',")
	lines.append('}')
	lines.append('')

	out_path.parent.mkdir(parents=True, exist_ok=True)
	out_path.write_text('\n'.join(lines) + '\n', encoding='utf-8')
	print(f'generate-fa-icons: wrote {len(canonical)} icons -> {out_path}')
	return 0


# MARK: main
def main(argv: list[str]) -> int:
	"""CLI entry."""
	repo = Path(__file__).resolve().parents[1]
	out  = repo / 'src' / 'ui-component-kit' / 'fonts' / 'fontAwesome.icons.ts'
	if len(argv) < 2:
		print('Usage: python scripts/generate-fa-icons.py path/to/icon-families.json', file=sys.stderr)
		return 1
	meta = Path(argv[1])
	if not meta.is_file():
		print(f'generate-fa-icons: missing {meta}', file=sys.stderr)
		return 1
	return generate(meta, out)


if __name__ == '__main__':
	raise SystemExit(main(sys.argv))
